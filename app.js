// Stage strength: same event/year appearing in semifinal and final should resolve to the furthest stage only.
function stageScore(title=""){
  if(title.includes("決勝結果") || title.includes("決勝進出") || title.includes("決勝進出者") || title.includes("決勝進出8") || title.includes("決勝進出9")) return 4;
  if(title.includes("準決勝") && !title.includes("敗者復活")) return 3;
  if(title.includes("敗者復活")) return 2;
  if(title.includes("予選")) return 1;
  return 0;
}
function stageLabel(title=""){
  if(title.includes("決勝結果")) return "決勝";
  if(title.includes("決勝")) return "決勝";
  if(title.includes("準決勝")) return "準決勝";
  if(title.includes("敗者復活")) return "敗者復活戦";
  if(title.includes("予選")) return "予選";
  return title || "出場";
}

// Build an index of unit appearances across all events.
// NOROSHI's team name is NOT indexed as a unit; its manzai/pin/conte units are.
const UNIT_INDEX = new Map();
function pushOccurrence(name, occ){
  if(!name || name==="—") return;
  const arr=UNIT_INDEX.get(name)||[];
  const same=arr.find(x=>x.eventKey===occ.eventKey);
  if(!same || occ.score>same.score){
    if(same) arr.splice(arr.indexOf(same),1);
    arr.push(occ);
  }
  UNIT_INDEX.set(name,arr);
}
DATA.forEach(d=>{
  const eventKey=`${d.year}-${d.type}`;
  (d.stages||[]).forEach(s=>{
    (s.entries||[]).forEach(e=>{
      const [rank,name,school,units=[]]=e;
      // Individual-event entries are units themselves.
      if(d.type==="individual"){
        pushOccurrence(name,{eventKey,year:d.year,type:d.type,event:d.event,stage:stageLabel(s.title),score:stageScore(s.title),rank,school});
      }
      // NOROSHI: index the three component units.
      (units||[]).forEach(([genre,unit])=>{
        pushOccurrence(unit,{eventKey,year:d.year,type:d.type,event:d.event,stage:stageLabel(s.title),score:stageScore(s.title),rank,school,genre,team:name});
      });
    });
  });
  (d.teamUnits||[]).forEach(([genre,unit])=>{
    pushOccurrence(unit,{eventKey,year:d.year,type:d.type,event:d.event,stage:"決勝",score:4,rank:"",school:d.school,genre,team:d.winner});
  });
});

function unitLink(name){
  const occ=UNIT_INDEX.get(name)||[];
  const distinct=new Set(occ.map(x=>x.eventKey));
  return distinct.size>=2
    ? `<button class="unit-link" data-unit="${encodeURIComponent(name)}">${name}<span aria-hidden="true"> ↗</span></button>`
    : `<span class="unit-plain">${name}</span>`;
}
function unitsHTML(units=[]){
  if(!units.length) return "";
  return `<div class="unit-composition">${units.map(([genre,name])=>
    `<span class="unit-chip"><em>${genre}</em>${unitLink(name)}</span>`).join("")}</div>`;
}

