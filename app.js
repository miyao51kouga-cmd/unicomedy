function searchBlob(d){
  const nested=(d.stages||[]).flatMap(s=>s.entries||[]).flat(3).join(" ");
  const teamUnits=(d.teamUnits||[]).flat().join(" ");
  return (Object.values(d).join(" ")+" "+nested+" "+teamUnits).toLowerCase();
}
function render(){
  const q=search.value.trim().toLowerCase();
  const t=typeFilter.value, y=yearFilter.value;
  const filtered=DATA.filter(d=>
    (!q||searchBlob(d).includes(q)) &&
    (t==="all"||d.type===t) &&
    (y==="all"||String(d.year)===y)
  );
  document.querySelector("#resultList").innerHTML=filtered.map(d=>{
    const accent=colorForSchool(d.school);
    return `<article class="result-row" data-event="${d.year}-${d.type}" style="--row-accent:${accent}">
      <div class="year">${d.year}</div><div class="type">${typeName(d.type)}</div>
      <div class="winner"><b><span class="winner-dot"></span>${d.winner}</b><small>${d.school}</small>${unitsHTML(d.teamUnits||[])}</div>
      <div class="awards">準優勝：${d.runnerUp}<br>3位：${d.third}<br>審査員賞：${d.judge}</div>
    </article>`;
  }).join("");
  document.querySelector("#empty").hidden=filtered.length!==0;
}
[search,typeFilter,yearFilter].forEach(el=>el.addEventListener("input",render)); render();

function stageHTML(stage,d){
  return `<section class="stage">
    <h3>${stage.title}</h3>
    ${stage.note?`<p class="stage-note">${stage.note}</p>`:""}
    <div class="entry-grid">
      ${(stage.entries||[]).map(e=>{
        const [rank,name,school,units=[]]=e;
        // Individual units get clickable history when they appear in multiple events.
        const displayName=d.type==="individual" ? unitLink(name) : `<b>${name}</b>`;
        return `<div class="entry">
          <span class="entry-rank">${rank||"•"}</span>
          <span>${displayName}<small>${school||""}</small>${unitsHTML(units||[])}</span>
        </div>`;
      }).join("")}
    </div>
  </section>`;
}
function openEvent(d){
  const accent=colorForSchool(d.school);
  const stages=(d.stages&&d.stages.length) ? d.stages.map(s=>stageHTML(s,d)).join("") :
    `<section class="stage"><h3>詳細データ整備中</h3><p class="stage-note">確認できる公式資料から順次追加します。</p></section>`;
  const sources=(d.sources||[]).map(([label,url])=>`<a class="source-chip" href="${url}" target="_blank" rel="noreferrer">${label} ↗</a>`).join("");
  dialogContent.innerHTML=`
    <header class="dialog-head" style="--event-accent:${accent}">
      <span class="dialog-kicker">${d.year} / ${typeName(d.type)}</span>
      <h2>${d.event}</h2>
      <div class="dialog-champion">優勝：${d.winner}</div>
      <div class="dialog-school">${d.school}</div>
      ${unitsHTML(d.teamUnits||[])}
      <div class="data-status">公開情報をもとに整理</div>
    </header>
    <div class="stage-wrap" style="--event-accent:${accent}">
      ${stages}
      ${sources?`<section class="stage"><h3>出典</h3>${sources}</section>`:""}
    </div>`;
  dialog.showModal();
}

