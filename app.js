// 同じNOROSHI大会の別ステージで3ユニットが判明していれば再利用する。
// 例: 準決勝香盤で構成が分かっているチームは決勝欄でも同じ3ユニットを表示。
function resolvedUnitsForTeam(d, teamName, suppliedUnits=[]){
  if(suppliedUnits && suppliedUnits.length) return suppliedUnits;
  if(d.type !== "noroshi") return suppliedUnits || [];

  for(const s of (d.stages||[])){
    for(const e of (s.entries||[])){
      const [,name,,units=[]] = e;
      if(name === teamName && units && units.length) return units;
    }
  }
  if(d.winner === teamName && d.teamUnits && d.teamUnits.length) return d.teamUnits;
  return [];
}

// 敗者復活戦の香盤に載っていたチームかどうか。
function cameFromRevival(d, teamName){
  if(d.type !== "noroshi") return false;
  return (d.stages||[]).some(s =>
    s.title.includes("敗者復活") &&
    (s.entries||[]).some(e => e[1] === teamName)
  );
}

// 詳細画面の表示順。
// 1. 決勝結果・決勝進出
// 2. 準決勝
// 3. 敗者復活戦
// 4. 予選・その他
function detailStageOrder(title=""){
  // まず決勝
  if(title.includes("決勝結果")) return 0;
  if(title.includes("決勝進出者") || title.includes("決勝進出8") || title.includes("決勝進出9")) return 1;

  // 「準決勝 → 決勝進出」は準決勝の結果として、準決勝グループの先頭へ
  if(title.includes("準決勝") && title.includes("決勝進出")) return 10;

  // 次に準決勝
  if(title.includes("準決勝")) return 11;

  // 次に敗者復活戦
  if(title.includes("敗者復活")) return 20;

  // 最後に予選
  if(title.includes("予選")) return 30;
  return 40;
}
function orderedStages(d){
  return [...(d.stages||[])].sort((a,b)=>{
    const oa=detailStageOrder(a.title), ob=detailStageOrder(b.title);
    if(oa!==ob) return oa-ob;

    // 同カテゴリ内は、結果・進出確定を先に、その後に香盤表
    const resultA = /決勝結果|→|決勝進出/.test(a.title) ? 0 : 1;
    const resultB = /決勝結果|→|決勝進出/.test(b.title) ? 0 : 1;
    if(resultA!==resultB) return resultA-resultB;

    const da = Number((a.title.match(/(\d+)日目/)||[])[1]||99);
    const db = Number((b.title.match(/(\d+)日目/)||[])[1]||99);
    return da-db;
  });
}

function stageHTML(stage,d){
  return `<section class="stage">
    <h3>${stage.title}</h3>
    ${stage.note?`<p class="stage-note">${stage.note}</p>`:""}
    <div class="entry-grid">
      ${(stage.entries||[]).map(e=>{
        const [rank,name,school,rawUnits=[]]=e;
        const units=resolvedUnitsForTeam(d,name,rawUnits);

        // 個人戦はユニット自体を履歴リンクにする。
        const displayName=d.type==="individual" ? unitLink(name) : `<b>${name}</b>`;

        // 敗者復活戦から勝ち上がって準決勝・決勝にいる場合だけ表示。
        const currentScore=stageScore(stage.title);
        const revivalBadge =
          d.type==="noroshi" &&
          currentScore>=3 &&
          cameFromRevival(d,name)
            ? `<span class="revival-origin">敗者復活戦から進出</span>`
            : "";

        return `<div class="entry">
          <span class="entry-rank">${rank||"•"}</span>
          <span>${displayName}${revivalBadge}<small>${school||""}</small>${unitsHTML(units)}</span>
        </div>`;
      }).join("")}
    </div>
  </section>`;
}
